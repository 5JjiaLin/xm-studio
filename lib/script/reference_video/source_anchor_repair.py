"""Restore uniquely located source excerpts with harmless Chinese layout changes.

This repairs content before the ordinary strict validators run; it does not relax
anchor, ordering, dialogue or coverage validation.
"""

from __future__ import annotations

import copy
import re
import unicodedata
from typing import Any

def _han(char: str) -> bool:
    return bool(char) and (
        "\u3400" <= char <= "\u9fff" or "\uf900" <= char <= "\ufaff"
        or "\U00020000" <= char <= "\U000323af"
    )


def _layout_projection(text: str) -> tuple[str, list[tuple[int, int]]]:
    """Keep raw offsets; ignore spacing only between Han / adjacent punctuation.

    Word boundaries in Latin and other spaced languages remain significant.
    No character, punctuation or Unicode compatibility substitution is allowed.
    """
    chars: list[str] = []
    offsets: list[tuple[int, int]] = []
    for match in re.finditer(r"\s+|\S", text):
        token = match.group()
        start, end = match.span()
        if token.isspace():
            left = text[start - 1] if start else ""
            right = text[end] if end < len(text) else ""
            if not left or not right:
                continue
            if (_han(left) and (_han(right) or unicodedata.category(right).startswith("P"))) or (
                _han(right) and unicodedata.category(left).startswith("P")
            ):
                continue
            token = " "
        chars.append(token)
        offsets.append((start, end))
    return "".join(chars), offsets


def restore_source_anchor_layout(content: dict[str, Any], source: str | None) -> dict[str, Any]:
    """Copy anchors that uniquely match the source after layout repair.

    Repeated passages and real content edits stay untouched for normal validation.
    A normalized anchor can already be a source substring while still differing at
    a boundary (for example, an AI-added final newline).  Those cases must also be
    replaced with the exact source slice so strict source bindings remain valid.
    Other fields, units and assets are never rewritten, and input is not mutated.
    """
    if not source or not isinstance(content.get("units"), list):
        return content
    projected_source, offsets = _layout_projection(source)
    repaired = content
    for index, unit in enumerate(content["units"]):
        if not isinstance(unit, dict):
            continue
        anchor = unit.get("source_text")
        if not isinstance(anchor, str):
            continue
        # Keep a byte-for-byte source excerpt, including real line endings.  The
        # projection below is only for AI layout drift that is not an exact slice
        # of the source (such as an added final newline).
        if anchor in source:
            continue
        projected_anchor, _ = _layout_projection(anchor)
        if not projected_anchor:
            continue
        start = projected_source.find(projected_anchor)
        if start < 0 or projected_source.find(projected_anchor, start + 1) >= 0:
            continue
        end = start + len(projected_anchor)
        exact = source[offsets[start][0]:offsets[end - 1][1]]
        if exact == anchor:
            continue
        if repaired is content:
            repaired = copy.deepcopy(content)
        repaired["units"][index]["source_text"] = exact
    return repaired


def preserve_source_bindings(content: dict[str, Any], baseline: dict[str, Any]) -> dict[str, Any]:
    """Keep server-owned source bindings when an AI repair returns full units.

    The generic draft-repair path may ask the model to return a complete ``units``
    array for an episode-level violation.  Bindings are provenance generated by the
    server, so a model response must not be allowed to add, remove, or rewrite them.
    Position-based restoration is safe only when the repair kept the original unit
    count; otherwise normal validation must reject the candidate for manual review.
    """
    units = content.get("units")
    baseline_units = baseline.get("units")
    if not isinstance(units, list) or not isinstance(baseline_units, list) or len(units) != len(baseline_units):
        return content

    repaired = content
    for index, baseline_unit in enumerate(baseline_units):
        if not isinstance(baseline_unit, dict) or "source_binding" not in baseline_unit:
            continue
        unit = units[index]
        if not isinstance(unit, dict) or unit.get("source_binding") == baseline_unit["source_binding"]:
            continue
        if repaired is content:
            repaired = copy.deepcopy(content)
        repaired["units"][index]["source_binding"] = copy.deepcopy(baseline_unit["source_binding"])
    return repaired
